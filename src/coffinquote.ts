(function () {
  const when = $('#coffinDate'), kind = $('#coffinKind'), words = $('#coffinWords');
  /* The same day gives everyone the same whisper, and the list goes all the way round before any repeat. */
  function show(): void {
    const now = new Date(), day = Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000);
    const [type, text] = COFFIN_QUOTES[(day * 37) % COFFIN_QUOTES.length];
    when.textContent = now.toLocaleDateString(undefined, { weekday: 'long', day: 'numeric', month: 'long' });
    kind.textContent = type; kind.dataset.kind = type.toLowerCase();
    words.textContent = text;
    const midnight = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1, 0, 0, 5).getTime();
    window.setTimeout(show, midnight - now.getTime());
  }
  show();
})();
